  private static Gson gson = new Gson();
  private static final String BASE_TEXTURE_PATH = "src/main/java/org/example/assets/Textures/";

  public static void loadTextures(String toLoad){
    Path path = Paths.get(BASE_TEXTURE_PATH+toLoad);
    int[][] texture;
    try{
      texture = gson.fromJson(new FileReader(path.toFile()), int[][].class);

    } catch (FileNotFoundException e){
      texture = DEFAULT_TEXTURE;
    }
    Color[][] parsedTex = parseTexture(texture);
    Texture tex = new Texture(parsedTex, 1);
    TextureRegistry.register(tex.getId(), tex);
  }

  private static Color[][] parseTexture(int[][] texture){
    Color[][] parsedTex = new Color[32][32];
    for(int i = 0;i < texture.length; i++){
      for (int j = 0; j < texture[i].length; j++){
        int toParse = texture[i][j];
        Color color = Color.byId(toParse);
        parsedTex[i][j] = color;
      }
    }
    return parsedTex;
  } 
